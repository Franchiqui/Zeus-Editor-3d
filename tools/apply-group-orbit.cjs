#!/usr/bin/env node
/**
 * apply-group-orbit.cjs
 * ---------------------------------------------------------------------------
 * Hace que la ROTACIÓN de un grupo (varios objetos seleccionados) ORBITE
 * alrededor del centro del grupo en vez de girar cada pieza sobre sí misma.
 *
 * Cambios (todos idempotentes):
 *   A) Refs nuevos: groupPivotRef (centro del grupo) y groupOrbitRef (giro).
 *   B) applyObjectTransform: las copias seleccionadas giran ALREDEDOR del
 *      pivote mientras el grupo orbita (giro en vivo).
 *   C) El manipulador grupal se queda fijo en el pivote durante la órbita.
 *   D) Al empezar el arrastre del gizmo: se calcula el centro del grupo.
 *   E) updateGizmoDrag: la pieza activa orbita en vivo y se guarda el giro.
 *   F) onPointerUp (multi-transform): el resto de piezas orbitan alrededor
 *      del pivote usando el giro acumulado.
 *   G) Al soltar: se limpian el pivote y el giro.
 */
